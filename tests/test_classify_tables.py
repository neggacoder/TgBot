"""Классификатор таблиц: у кого чат один, у кого правда два.

Ошибка здесь стоит смешанных данных двух чатов без пути назад, поэтому
проверяются конкретные решения на понятных примерах, а не «работает».
"""

from __future__ import annotations

from tools import classify_tables


def test_колонка_уходит_отовсюду():
    """Решение владельца: данные к чатам не привязаны вовсе. Всё — люди,
    позывные, муты, сообщения, экономика — принадлежит одному рабочему чату,
    а второй нужен только как адрес для уведомлений и переписки."""
    for таблица in ("known_users", "current_users", "message_stats",
                    "message_daily", "call_signs", "mutes", "warns",
                    "economy_wallets", "farm_plots"):
        assert classify_tables.решение(таблица) == "убрать", таблица


def test_игровые_таблицы_теряют_колонку():
    """Играть в чате заявок нельзя: заслон пускает туда только ответы админов
    и нажатия кнопок."""
    for таблица in ("economy_wallets", "farm_plots", "casino_wallets",
                    "businesses", "user_pets", "fishing_stats"):
        assert classify_tables.решение(таблица) == "убрать", таблица


def test_новая_таблица_тоже_без_колонки():
    """Правило теперь общее: данные к чатам не привязаны. Заведут таблицу с
    chat_id — она тоже пойдёт в «убрать», и это верно: разделять по чатам
    больше нечего."""
    assert classify_tables.решение("таблица_которой_нет") == "убрать"


def test_таблицы_собираются_из_обоих_источников():
    """Схема лежит в двух местах: базовые таблицы в schema.sql, остальные
    создаются на ходу в db.py. Прочитай только db.py — и known_users,
    message_stats, nicknames, call_signs и mutes выпадут из отчёта молча, а
    значит и из миграции: колонка у них осталась бы, и половина базы жила бы
    по старым правилам."""
    найдено = classify_tables.таблицы_с_колонкой()
    assert len(найдено) > 90, "схема читается неверно — таблиц слишком мало"
    # из db.py
    assert "economy_wallets" in найдено
    # из schema.sql
    for имя in ("known_users", "message_stats", "nicknames", "call_signs",
                "mutes"):
        assert имя in найдено, f"{имя} потеряна — читается только один источник"


def test_спорных_не_осталось():
    """Каждая таблица разобрана: либо правилом, либо руками с обоснованием.
    «Спорные» в отчёте — это работа, не сделанная до конца, и владельцу
    пришлось бы решать её вслепую."""
    итог = classify_tables.разбор()
    assert not итог["спорные"], f"не разобраны: {итог['спорные']}"


def test_у_разобранных_руками_есть_обоснование():
    """Решение без причины нечем проверить: через месяц никто не вспомнит,
    почему у таблицы убрали колонку."""
    for таблица, (решение, причина) in classify_tables.РАЗОБРАНЫ.items():
        assert решение in ("оставить", "убрать"), таблица
        assert len(причина) > 15, f"{таблица}: обоснование слишком короткое"


def test_строки_второго_чата_известны_заранее():
    """Список таблиц, куда второй чат мог что-то записать, нужен миграции: там
    и только там возможно совпадение ключей при слиянии."""
    assert "known_users" in classify_tables.ОБА_ЧАТА
    assert "message_stats" in classify_tables.ОБА_ЧАТА
    assert "economy_wallets" not in classify_tables.ОБА_ЧАТА


def test_настройки_не_считаются_чатовой_таблицей():
    """У settings колонки notify_chat_id и complaint_chat_id — это ЗНАЧЕНИЯ,
    а не разбиение по чатам. Разбор по подстроке однажды уже записал её в
    чатовые."""
    assert "settings" not in classify_tables.таблицы_с_колонкой()
