    for правило in re.finditer(r"([^{}]+)\{[^}]*min-width:\s*0", CSS):
        for сел in правило.group(1).split(","):
            база = сел.strip().split(" ")[0].split(">")[0].strip()
            if база.startswith("."):
                защищены.add(база)
    голые = sorted(ряды - защищены - колонки)
    assert not голые, (
        "ряды со space-between без min-width: 0 у детей — их содержимое "
        f"обрежется на телефоне: {голые}")


