def test_высота_одна_на_обе_семьи_кнопок():
    """В панели ДВЕ семьи кнопок: `button.primary/.danger/.ghost` в админской
    части и `.btn` в кабинете участника. Правило, написанное только для одной,
    оставляет вторую половину экрана прежней высоты — и выглядит сделанным,
    пока не откроешь телефон."""
    правило = re.search(r"([^{}]+)\{\s*min-height:\s*var\(--control-h\);\s*\}", CSS)
    assert правило, "нет общего правила высоты"
    селекторы = правило.group(1)
    for семья in ("button.ghost", "button.primary", "button.danger", ".btn",
                  "select", "input[type=text]"):
        assert семья in селекторы, f"{семья} осталась вне общей высоты"
    # А метки — наоборот, вне: класс .chip носят и кнопки (фишки казино,
    # фильтры), и пилюли вроде «вы здесь» в <span>. Метку не нажимают, и
    # растянутая под палец она разносит строку тегов.
    assert re.search(r"(?<!button)(?<!\w)\.chip[,\s]", селекторы) is None, (
        "под общую высоту попали и метки-пилюли, а не только кнопки-фишки")


def test_никто_не_задаёт_высоту_мимо_переменной():
    """Разнобой 34/36/38/40/44 по медиазапросам и давал ощущение кривой
    вёрстки: соседние кнопки отличались на два-четыре пикселя. Одно значение —
    одна переменная."""
    свои = []
    for m in re.finditer(r"([^{};]+)\{[^{}]*?min-height:([^;}]+)", БЕЗ_ЗАМЕТОК):
        селектор = m.group(1).strip().split("\n")[-1].strip()
        значение = m.group(2).strip()
        if значение == "var(--control-h)" or "vh" in значение or значение in ("0", "2px"):
            continue
        if any(и in селектор for и in ВЫСОТА_СВОЯ):
            continue
        свои.append(f"{селектор} → {значение}")
    assert not свои, f"высота задана мимо --control-h: {свои}"


