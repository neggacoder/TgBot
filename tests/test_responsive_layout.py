def test_у_карточек_одни_поля():
    """Две соседние плитки с полями 10/14 и 14/14 читаются как сбитая сетка,
    хотя каждая по отдельности выглядит нормально. Ровно так и было: половина
    плиток так, половина эдак, а на телефоне переопределения доставались не
    всем экранам — часть карточек ужималась, часть нет.

    Теперь поля приходят из --pad-panel (крупный блок) или --pad-card
    (плитка в сетке), и телефон правит одно значение вместо десятка правил."""
    чужие = []
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", БЕЗ_ЗАМЕТОК):
        сел, тело = " ".join(m.group(1).split()), m.group(2)
        if "border-radius" not in тело or "padding:" not in тело:
            continue
        if any(и in сел for и in НЕ_КАРТОЧКА):
            continue
        поля = re.search(r"padding:\s*([^;]+)", тело).group(1).strip()
        if поля not in ("var(--pad-panel)", "var(--pad-card)", "var(--pad-head)"):
            чужие.append(f"{сел[:44]} → {поля}")
    assert not чужие, f"карточки с собственными полями: {чужие}"


def test_на_телефоне_карточки_ужимаются_все_разом():
    """Поля правятся ОДНИМ значением на переменную. Отдельные правила на
    экран — это ровно та беда, из которой всё и выросло: часть экранов правку
    получает, часть нет."""
    мобильный = _медиа_блок("@media (max-width: 760px)")
    for токен in ("--pad-panel", "--pad-card", "--pad-head"):
        m = re.search(rf"{токен}:\s*var\(--gap-\d\)", мобильный)
        assert m, f"{токен} на телефоне не ужимается"
    свои = re.findall(r"([\w.\- ]+)\{[^{}]*padding:\s*var\(--gap-\d\)[^{}]*\}",
                      мобильный)
    лишние = [с.strip() for с in свои
              if "card" in с or "tile" in с or "sheet" in с or "table" in с]
    assert not лишние, f"поля карточек всё ещё правятся поштучно: {лишние}"


def test_цифры_одной_ширины_везде():
    """Числа в панели повсюду. Пропорциональные цифры разной ширины дёргают
    строку на каждом обновлении — таймер дрожит, столбец сумм пляшет.

    Правило обязано стоять ПОСЛЕ всех `font: inherit`: сокращённое свойство
    font сбрасывает font-variant-numeric в normal, и любое из них ниже молча
    отменило бы табличные цифры внутри кнопок и полей."""
    хвост = БЕЗ_ЗАМЕТОК.rstrip() + "\n"
    m = re.search(r"([^{}]*)\{\s*font-variant-numeric:\s*tabular-nums;\s*\}\s*$", хвост)
    assert m, "общего правила табличных цифр нет или оно не последнее в файле"
    for семья in ("body", "button", "input", "select", ".btn"):
        assert семья in m.group(1), f"{семья} осталась с прыгающими цифрами"
    assert хвост.rindex("font: inherit") < m.start(), (
        "ниже правила есть `font: inherit` — он сбросит табличные цифры")


def test_нет_жёстких_ширин_шире_телефона():
    """width: 460px у модального окна уже уводил страницу вбок. Ширину задают
    либо через min(), либо внутри медиазапроса для широких экранов."""
    жёсткие = []
    for m in re.finditer(r"(?<!max-)(?<!min-)width:\s*(\d{3,})px", CSS):
        значение = int(m.group(1))
        if значение <= 360:
            continue
        начало = CSS.rfind("@media", 0, m.start())
        конец = CSS.find("}", начало) if начало >= 0 else -1
        внутри_медиа = начало >= 0 and "min-width" in CSS[начало:конец]
        if not внутри_медиа:
            жёсткие.append(m.group(0))
    assert not жёсткие, f"жёстче экрана телефона: {жёсткие}"


