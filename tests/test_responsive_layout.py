def _правила(блок: str, селектор: str) -> str:
    """Все тела правил этого селектора в блоке, склеенные. Правил на один
    селектор бывает несколько (они дописывались по мере правок), и брать
    первое попавшееся — значит проверять не то."""
    куски, i = [], блок.find(селектор + " {")
    while i >= 0:
        конец = блок.index("}", i)
        куски.append(блок[i:конец])
        i = блок.find(селектор + " {", конец)
    assert куски, f"нет правил для {селектор}"
    return "\n".join(куски)


