def test_у_каждого_поля_сказано_про_автозаполнение():
    """Менеджер паролей предлагал логин в поле ставки казино.

    Не случайность: форма входа никуда не девается, она просто спрятана
    классом. Менеджер читает страницу целиком и цепляется к любому полю, про
    которое не сказано обратного, — а не сказано было про пятьдесят пять
    полей из семидесяти. Ставка просто оказалась первой, куда ткнули.

    Поэтому правило сплошное: у каждого поля ввода autocomplete задан явно.
    Молчание тут означает «решай сам», и браузер решает как умеет."""
    голые = []
    for файл in ("app.js", "index.html"):
        текст = (СТАТИКА / файл).read_text(encoding="utf-8")
        for тег in re.findall(r"<input\b[^>]*>", текст):
            вид = re.search(r'type="(\w+)"', тег)
            вид = вид.group(1) if вид else "text"
            # Флажкам и выбору файла автозаполнению предложить нечего.
            if вид in ("checkbox", "radio", "file", "hidden"):
                continue
            if "autocomplete=" not in тег:
                голые.append(f"{файл}: {' '.join(тег.split())[:70]}")
    assert not голые, f"поля без autocomplete — в них полезет менеджер паролей: {голые}"


