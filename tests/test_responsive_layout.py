"""Вёрстка панели на телефоне.

Проверяется не «красиво», а то, что ломает пользование и чинится один раз:
страница не должна ехать вбок, поля не должны заставлять iOS увеличивать
масштаб, в кнопку должно попадать пальцем.
"""

from __future__ import annotations

import pathlib
import re

import pytest

СТАТИКА = pathlib.Path(__file__).resolve().parent.parent / "webpanel" / "static"
CSS = (СТАТИКА / "style.css").read_text(encoding="utf-8")
# Файл на треть состоит из заметок — почему сделано именно так. Заметки
# цитируют и сами правила («каждое наше font: inherit»), поэтому проверки,
# которые ищут ОБЪЯВЛЕНИЯ, обязаны смотреть в текст без них: иначе процитированное
# в комментарии правило засчитывается как настоящее.
БЕЗ_ЗАМЕТОК = re.sub(r"/\*.*?\*/", "", CSS, flags=re.S)


def _без_заметок_js(текст: str) -> str:
    """То же для кода: строки-заметки прочь.

    Ровно та же ловушка, что и в стилях, и она уже сработала: заслон на
    «колесо не должно перескакивать» искал слово offsetWidth — и находил его
    в заметке, которая объясняла, зачем эта строка нужна. Строку можно было
    удалить, заметку оставить, и проверка бы молчала."""
    return "\n".join(с for с in текст.split("\n") if not с.lstrip().startswith("//"))


@pytest.mark.parametrize("страница", ["index.html", "webapp.html"])
def test_у_страницы_есть_метатег_масштаба(страница):
    """Без него мобильный браузер рисует страницу как десктопную и ужимает —
    всё становится нечитаемым, и никакие медиазапросы не срабатывают."""
    html = (СТАТИКА / страница).read_text(encoding="utf-8")
    assert 'name="viewport"' in html
    assert "width=device-width" in html


def _медиа_блок(условие: str) -> str:
    """Содержимое медиазапросов с таким условием — и только их, а не весь
    хвост файла: со срезом до конца проверка проходила бы и на селекторе из
    соседнего блока. Блоков с одним условием может быть несколько (правила
    дописываются по мере появления экранов) — склеиваем все."""
    куски = []
    начало = CSS.find(условие)
    while начало >= 0:
        открыта = CSS.index("{", начало)
        глубина, i = 1, открыта + 1
        while глубина and i < len(CSS):
            глубина += (CSS[i] == "{") - (CSS[i] == "}")
            i += 1
        куски.append(CSS[открыта:i])
        начало = CSS.find(условие, i)
    assert куски, f"нет медиазапроса {условие}"
    return "\n".join(куски)


def test_страница_не_едет_вбок():
    """clip, а не hidden, и только на body: overflow на html делает его
    контейнером прокрутки и ломает position: sticky — а на нём тут держатся
    боковое меню, шапки таблиц и полоса уведомлений."""
    assert "overflow-x: clip" in CSS
    assert "overflow-x: hidden" not in CSS
    assert re.search(r"html,\s*body\s*\{[^}]*max-width:\s*100%", CSS)
    assert "position: sticky" in CSS, "если sticky ушёл — правило можно упростить"


def test_широкое_прокручивается_внутри_себя():
    """Таблицы и ряд вкладок шире телефона — они обязаны листаться сами, а не
    тянуть за собой страницу."""
