def test_дети_сеток_кабинета_умеют_сжиматься():
    """Ребёнок сетки по умолчанию НЕ сжимается уже своего содержимого. Пока
    внутри текст, это незаметно; стоит появиться широкому — и колонка
    растягивается по нему, а вместе с ней вся вкладка.

    Так и вышло с лентой рулетки: сорок одна клетка по 56 пикселей, больше
    двух тысяч — карточка казино разъезжалась на пять экранов телефона.
    Обрезка от этого не спасала: overflow прячет лишнее, но ширину содержимого
    всё равно считают по нему."""
    for родитель in (".member-content", ".member-block"):
        assert re.search(rf"{re.escape(родитель)} > \*[^{{}}]*\{{[^{{}}]*min-width:\s*0",
                         БЕЗ_ЗАМЕТОК), f"дети {родитель} не умеют сжиматься"


def _токен(имя: str) -> int:
    """Значение переменной из :root в пикселях.

    Проверки должны читать РАЗМЕР, а не текст правила: пока размеры стояли
    числами, проверка искала «16px» подстрокой и держалась. Стоило вынести их
    в переменные — она упала, хотя вёрстка не изменилась ни на пиксель.
    Теперь переменная разворачивается, и проверка снова про размер."""
    m = re.search(rf"^\s*{re.escape(имя)}:\s*(\d+)px", CSS, re.M)
    assert m, f"нет переменной {имя}"
    return int(m.group(1))


def test_поля_не_заставляют_ios_увеличивать_масштаб():
    """Меньше 16px — и Safari увеличивает страницу при фокусе, а вернуть
    масштаб потом нечем."""
    m = re.search(r"input,\s*select,\s*textarea\s*\{\s*font-size:\s*var\((--[\w-]+)\)", CSS)
    assert m, "у полей на телефоне не задан размер шрифта"
    assert _токен(m.group(1)) >= 16, "Safari увеличит страницу при фокусе"


