"""Сопоставление фильтра слов (word_filter.py).

Стережём главное свойство выбранного режима — совпадение по ЦЕЛОМУ слову:
запрещённое слово не должно ложно срабатывать внутри других слов («класс» от
«асс»), но должно ловиться при любом регистре и любой пунктуации вокруг.
"""

from __future__ import annotations

import pytest

from word_filter import find_banned, has_banned, normalize

BANNED = ["спам", "реклама", "плохая фраза"]


# ---------------------------------------------------------------------------
# Срабатывает — целое слово, любой регистр, любая пунктуация вокруг
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("text", [
    "это спам",
    "СПАМ!",
    "куплю рекламу... то есть реклама",
    "спам, реклама и прочее",
    "текст\nспам\nтекст",
    "(спам)",
    "спам?",
])
def test_запрещённое_слово_ловится(text):
    assert has_banned(text, BANNED)


def test_возвращается_само_сработавшее_слово():
    assert find_banned("тут реклама", BANNED) == "реклама"


def test_регистр_не_важен():
    assert has_banned("СпАм", BANNED)


def test_фраза_целиком():
    assert has_banned("это плохая фраза здесь", BANNED)


# ---------------------------------------------------------------------------
# НЕ срабатывает — слово внутри другого слова (ложные срабатывания)
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("text", [
    "спамить",       # спам внутри слова
    "антиспам",
    "рекламный баннер",   # реклама → рекламный: другое слово
    "класс",         # классическая ловушка подстроки
    "трасса",
    "",
    "обычное сообщение",
])
def test_ложных_срабатываний_нет(text):
    assert not has_banned(text, BANNED)


def test_фраза_не_срабатывает_внутри_слова():
    assert not has_banned("неплохая фразочка", ["плохая фраз"])


# ---------------------------------------------------------------------------
# Граничные случаи
# ---------------------------------------------------------------------------

def test_пустой_список_ничего_не_ловит():
    assert find_banned("спам реклама", []) is None


def test_пустой_текст():
    assert find_banned("", BANNED) is None
    assert find_banned(None, BANNED) is None


def test_пустые_записи_в_списке_игнорируются():
    assert find_banned("привет", ["", "   ", "\n"]) is None


def test_нормализация():
    assert normalize("  СПАМ  ") == "спам"
    assert normalize("Ёлка") == "ёлка"


def test_ё_и_е_различаются():
    """casefold не приравнивает ё к е — «ёж» не удалит «еж». Это осознанно:
    склеивать их — отдельное решение, которого фильтр не принимает."""
    assert has_banned("ёж укусил", ["ёж"])
    assert not has_banned("еж укусил", ["ёж"])
