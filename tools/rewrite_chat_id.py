"""Убрать первый параметр chat_id из объявлений и вызовов.

Правится по РАЗБОРУ кода, а не по тексту. Причина простая: «chat_id»
встречается и там, где он остаётся, — отправка в телеграм (`send_message`),
адреса чатов в настройках, заслон `chat_scope_allows`. Регулярка по имени
переписала бы и их, и бот замолчал бы, не сказав ни слова об ошибке.

Второе правило: всё, в чём скрипт не уверен, он НЕ трогает и печатает
списком. Скрипт, который додумывает в спорном месте, ломает молча — а именно
молчаливых поломок в четырёх тысячах правок и надо бояться больше всего.
Отказов ожидается немного, и они правятся руками.
"""

from __future__ import annotations

import ast
import re

# Как выглядит чат первым аргументом. Список ЗАКРЫТЫЙ: всё, чего здесь нет, —
# отказ. Лучше сорок мест посмотреть глазами, чем одно переписать неверно.
ВИДЫ_ЧАТА = re.compile(
    r"^\s*("
    # Само имя и любые его вариации: target_chat_id, roles_chat_id,
    # complaint_chat_id, anon_chat_id. Всё, что названо чатом, чатом и
    # является — это единственное допущение, и оно проверяется прогоном.
    r"\w*chat_id"
    # Обращения к сообщению: message.chat.id и родня.
    r"|(?:\w+\.)*chat\.id"
    # Значение из строки базы или тела запроса: int(good[\"chat_id\"]),
    # body.chat_id.
    r"|int\(\s*\w+\[[\"\']chat_id[\"\']\]\s*\)"
    r"|(?:\w+\.)+chat_id"
    # Помощник, отдающий чат: _pets_admin_chat_id(), work_chat_id().
    r"|\w*chat_id\(\s*\)"
    # Константы тестов и явные числа.
    r"|CHAT|ЧАТ|РАБОЧИЙ|рабочий(?:_чат)?|-?\d+"
    r")\s*$"
)


def функции_с_чатом(исходник: str) -> set[str]:
    """Имена функций, у которых ПЕРВЫЙ позиционный параметр — chat_id.

    Только первый: у `add_log(kind, chat_id=0)` чат стоит дальше, и вырезать
    его вслепую значило бы сдвинуть остальные аргументы.
    """
    дерево = ast.parse(исходник)
    найдено: set[str] = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef)):
            позиционные = узел.args.args
            if позиционные and позиционные[0].arg == "chat_id":
                найдено.add(узел.name)
    return найдено


def убрать_параметр(исходник: str, имена: set[str]) -> str:
    """Убирает первый параметр из объявлений перечисленных функций.

    Два случая: сигнатура в одну строку и разбитая по строкам — в db.py
    длинных сигнатур большинство.
    """
    строки: list[str | None] = исходник.split("\n")
    for i, строка in enumerate(строки):
        if строка is None:
            continue
        # Однострочная сигнатура: def имя(chat_id: int, …
        m = re.match(r"(\s*(?:async )?def (\w+)\()chat_id(?:: int)?,\s*", строка)
        if m and m.group(2) in имена:
            строки[i] = m.group(1) + строка[m.end():]
            continue
        # Многострочная: имя(  на прошлой строке, chat_id на этой.
        if re.match(r"\s*chat_id(?:: int)?,\s*", строка) and i:
            выше = строки[i - 1] or ""
            имя = re.search(r"(?:async )?def (\w+)\(\s*$", выше)
            if имя and имя.group(1) in имена:
                остаток = re.sub(r"^\s*chat_id(?:: int)?,\s*", "", строка)
                строки[i] = ("    " + остаток.strip()) if остаток.strip() else None
    return "\n".join(с for с in строки if с is not None)


def _разделить(аргументы: str) -> list[str]:
    """Аргументы верхнего уровня.

    Скобки и кавычки внутри не считаются разделителями: без этого
    `add_coins(chat_id, max(1, x), note)` разобрался бы по запятой внутри
    max() и первым аргументом оказалось бы полвыражения.
    """
    части: list[str] = []
    глубина, текущая, кавычка = 0, "", None
    for символ in аргументы:
        if кавычка:
            текущая += символ
            if символ == кавычка:
                кавычка = None
            continue
        if символ in "\"'":
            кавычка = символ
        elif символ in "([{":
            глубина += 1
        elif символ in ")]}":
            глубина -= 1
        if символ == "," and глубина == 0:
            части.append(текущая)
            текущая = ""
            continue
        текущая += символ
    if текущая.strip():
        части.append(текущая)
    return части


def убрать_аргумент(исходник: str, имена: set[str],
                    префиксы: set[str]) -> tuple[str, list[str], int]:
    """Убирает первый аргумент у вызовов вида `префикс.имя(чат, …)`.

    Возвращает (новый текст, отказы, сколько переписано). Отказ — вызов, у
    которого первый аргумент не похож ни на один известный вид чата: имя
    переменной со смыслом, вызов функции, именованный параметр.

    Счётчик нужен отчёту: считать правки разницей строк нельзя — многострочный
    вызов схлопывается и сдвигает всё ниже, и одна правка выглядит как тысяча.
    """
    отказы: list[str] = []
    правок = 0
    новый = исходник
    for имя in sorted(имена):
        for префикс in sorted(префиксы):
            начало = f"{префикс}.{имя}("
            i = 0
            while True:
                i = новый.find(начало, i)
                if i < 0:
                    break
                открыта = i + len(начало)
                глубина, j = 1, открыта
                while j < len(новый) and глубина:
                    if новый[j] in "([{":
                        глубина += 1
                    elif новый[j] in ")]}":
                        глубина -= 1
                    j += 1
                внутри = новый[открыта:j - 1]
                части = _разделить(внутри)
                if not части:
                    i = j
                    continue
                if not ВИДЫ_ЧАТА.match(части[0]):
                    отказы.append(f"{префикс}.{имя}({части[0].strip()[:40]}…)")
                    i = j
                    continue
                остаток = внутри[len(части[0]):].lstrip()
                if остаток.startswith(","):
                    остаток = остаток[1:].lstrip()
                новый = новый[:открыта] + остаток + новый[j - 1:]
                правок += 1
                i = открыта
    return новый, отказы, правок
