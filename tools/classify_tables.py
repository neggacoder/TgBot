def таблицы_с_колонкой() -> list[str]:
    """Таблицы, у которых в схеме есть chat_id.

    Читаем ИСХОДНИКИ, а не живую базу: скрипт должен работать там, где базы
    нет, — иначе классификацию нельзя ни проверить тестом, ни обсудить до
    подключения к серверу.

    Источников два, и это не мелочь. Базовые таблицы (люди, сообщения,
    модерация) объявлены в schema.sql, остальные создаются на ходу в db.py.
    Прочитай только db.py — и known_users, message_stats, nicknames, call_signs
    и mutes молча выпадут из отчёта, то есть он соврёт, что чужих данных там
    нет. Именно эти таблицы и должны СОХРАНИТЬ колонку.
    """
    найдено = set()
    for файл in ("db.py", "schema.sql"):
        путь = КОРЕНЬ / файл
        if not путь.exists():
            continue
        текст = путь.read_text(encoding="utf-8")
        начала = [m.start() for m in re.finditer(r"CREATE TABLE IF NOT EXISTS", текст)]
        начала.append(len(текст))
        for i, старт in enumerate(начала[:-1]):
            имя = re.match(r"CREATE TABLE IF NOT EXISTS `?(\w+)`?", текст[старт:])
            if имя is None:
                continue
            # Блок режем по СЛЕДУЮЩЕМУ CREATE TABLE, а не по «);» или закрывающей
            # кавычке: у части таблиц конец записан иначе, окно уезжало в
            # соседнюю таблицу и приносило оттуда чужую колонку. Так settings —
            # у которой чатовых колонок нет вовсе, только значения
            # notify_chat_id и complaint_chat_id — попадала в список.
            тело = текст[старт:начала[i + 1]]
            # Именно chat_id, а не *_chat_id: «notify_chat_id» — это НАСТРОЙКА,
            # значение, а не разбиение таблицы по чатам.
            if re.search(r"(?<![\w])chat_id\b", тело):
                найдено.add(имя.group(1))
        найдено |= set(re.findall(
            r'_add_column_if_missing\(\s*"(\w+)",\s*"chat_id"', текст))
    return sorted(найдено)


