def решение(таблица: str) -> str:
    """«оставить» | «убрать».

    Спорных больше нет: по решению владельца данные к чатам не привязаны
    вовсе. Таблица сохраняет колонку, только если та не разделяет строки, а
    хранит сам идентификатор чата (см. НЕ_ТРОГАТЬ).
    """
    if таблица in НЕ_ТРОГАТЬ:
        return "оставить"
    return "убрать"


def почему(таблица: str) -> str:
    """Обоснование решения — пусто, если таблица разобрана правилом."""
    return РАЗОБРАНЫ.get(таблица, ("", ""))[1]


def разбор() -> dict[str, list[str]]:
    итог: dict[str, list[str]] = {"оставить": [], "убрать": [], "спорные": []}
    for таблица in таблицы_с_колонкой():
        итог[решение(таблица)].append(таблица)
    return итог


def main() -> None:
    итог = разбор()
    for имя in ("оставить", "убрать", "спорные"):
        print(f"\n=== {имя} ({len(итог[имя])}) ===")
        for таблица in итог[имя]:
            обоснование = почему(таблица)
            print(f"   {таблица:28} {обоснование}")
    print("\nСпорные решает человек до этапа 4: молчаливое «убрать» смешает "
          "данные двух чатов, и разобрать обратно будет нечем.")


