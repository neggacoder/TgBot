// Проверка МАТЕМАТИКИ анимаций казино: колесо, кость, монета.
//
// Зачем отдельно от остальных прогонов. Ошибка в угле не видна: колесо так же
// красиво крутится и так же плавно останавливается — просто не на том числе.
// Кость так же кувыркается и падает — просто не той гранью. Монета так же
// звонко переворачивается — просто не той стороной. Ни check_loaders (экран
// открылся), ни check_actions (запрос ушёл) этого не поймают, а глазами
// сверять с текстом итога никто не станет.
//
// Запуск: node tools/check_casino_anim.js   (из корня проекта)
const fs = require("fs");
const path = require("path");
const src = fs.readFileSync(
  path.join(__dirname, "..", "webpanel", "static", "app.js"), "utf8");

// Берём два куска: объявление колеса с математикой и рисовалку. Обе части
// чистые — ни браузера, ни сервера им не нужно, остальной файл тоже.
const кусок = (от, до) => {
  const i = src.indexOf(от), j = src.indexOf(до);
  if (i < 0 || j < 0 || j <= i) {
    console.log(`✗ не нашлось «${от}» — проверка смотрит не туда`);
    process.exit(1);
  }
  return src.slice(i, j);
};
// Заглушки для тех кусков, что двигают разметку. Нужны, чтобы позвать сами
// броски и посмотреть, доходит ли дело до конца.
const узлы = {};
global.$ = (сел) => (узлы[сел] ||= {
  style: {}, textContent: "", disabled: false, parentElement: null,
  animate: () => {}, offsetWidth: 100,
});
global.window = { matchMedia: () => ({ matches: false }) };
global.localStorage = { getItem: () => null, setItem() {} };

const { WHEEL_ORDER, WHEEL_STEP, WHEEL_TURNS, wheelAngle, wheelHtml, _casino,
        DIE_SIDES, DIE_FACE, DIE_TURNS_X, DIE_TURNS_Y, dieAngles, DIE_PIPS,
        dieFaceHtml, die3dHtml, coinHtml, COIN_FACE, COIN_TURNS, coinAngle,
        spinWheel, rollDie, flipCoin } =
  new Function(
    кусок("const _casino = {", "function casinoSay") +
    кусок("function wheelHtml()", "function casinoTableHtml") +
    кусок("function крутить(", "async function casinoPlay") +
    "\n;return {WHEEL_ORDER, WHEEL_STEP, WHEEL_TURNS, wheelAngle, wheelHtml, _casino,"
    + " DIE_SIDES, DIE_FACE, DIE_TURNS_X, DIE_TURNS_Y, dieAngles, DIE_PIPS,"
    + " dieFaceHtml, die3dHtml, coinHtml, COIN_FACE, COIN_TURNS, coinAngle,"
    + " spinWheel, rollDie, flipCoin};")();

let ошибок = 0;
const плохо = (текст) => { console.log("✗ " + текст); ошибок++; };
// Проверки, которым нужно дождаться таймеров: копим и смотрим в самом конце.
const ожидания = [];

// --- сам порядок ------------------------------------------------------------
// Дубль в списке делает одно число недостижимым, а другое — выпадающим не на
// своём месте. Опечатку в тридцати семи числах глазами не видно.
if (WHEEL_ORDER.length !== 37) плохо(`чисел на колесе ${WHEEL_ORDER.length}, а не 37`);
const набор = new Set(WHEEL_ORDER);
if (набор.size !== WHEEL_ORDER.length) плохо("на колесе есть повторы");
for (let n = 0; n <= 36; n++) if (!набор.has(n)) плохо(`числа ${n} нет на колесе`);

// Настоящее колесо чередует красное и чёрное. Проверяем по правилам бота:
// красные числа заданы в casino_actions.RED_NUMBERS.
const КРАСНЫЕ = new Set([1, 3, 5, 7, 9, 12, 14, 16, 18, 19, 21, 23, 25, 27, 30, 32, 34, 36]);
for (let i = 0; i < WHEEL_ORDER.length; i++) {
  const n = WHEEL_ORDER[i], сосед = WHEEL_ORDER[(i + 1) % WHEEL_ORDER.length];
  if (n === 0 || сосед === 0) continue;
  if (КРАСНЫЕ.has(n) === КРАСНЫЕ.has(сосед)) {
    плохо(`${n} и ${сосед} стоят рядом и одного цвета — порядок не как на колесе`);
    break;
  }
}

// --- угол -------------------------------------------------------------------
// Каждое число обязано вставать ровно под стрелкой (наверху), с какого бы
// положения колесо ни начинало.
for (const было of [0, 137.5, 3600, 12345.678]) {
  for (const n of WHEEL_ORDER) {
    const угол = wheelAngle(было, n);
    const место = WHEEL_ORDER.indexOf(n);
    // Сектор стоит под углом место*шаг от верха; после поворота на «угол»
    // он должен оказаться на нуле.
    const где = (((место * WHEEL_STEP + угол) % 360) + 360) % 360;
    const мимо = Math.min(где, 360 - где);
    if (мимо > 0.001) {
      плохо(`число ${n} встаёт мимо стрелки на ${мимо.toFixed(2)}°`);
      break;
    }
    // Колесо всегда доворачивается вперёд, и не на пол-оборота: иначе оно
    // будет то дёргаться на месте, то отматываться назад.
    if (угол < было + 360 * WHEEL_TURNS) {
      плохо(`число ${n}: колесо крутится меньше ${WHEEL_TURNS} оборотов`);
      break;
    }
  }
}

// Число не с колеса (сервер вернул мусор) не должно дёргать колесо вовсе.
if (wheelAngle(720, 99) !== 720) плохо("чужое число всё равно крутит колесо");

// --- разметка ---------------------------------------------------------------
// Колесо рисуется по тому же списку, по которому считается угол. Если рисовать
// и считать разойдутся, колесо будет останавливаться не на том числе — и это
// опять же будет выглядеть совершенно нормально.
_casino.state = { reds: [1, 3, 5, 7, 9, 12, 14, 16, 18, 19, 21, 23, 25, 27, 30, 32, 34, 36] };
_casino.angle = 0;
_casino.last = null;
const разметка = wheelHtml();

const секторов = (разметка.match(/class="wheel-slot /g) || []).length;
if (секторов !== 37) плохо(`секторов нарисовано ${секторов}, а не 37`);
const числа = [...разметка.matchAll(/class="wheel-num"[^>]*>(\d+)</g)].map((m) => Number(m[1]));
if (числа.length !== 37) плохо(`подписей нарисовано ${числа.length}, а не 37`);
for (const n of WHEEL_ORDER) {
  if (числа.filter((x) => x === n).length !== 1) плохо(`число ${n} нарисовано не один раз`);
}
// Подписи стоят в том же порядке, в каком считается угол: иначе колесо
// доворачивается к сектору, где нарисовано другое число.
if (числа.join(",") !== WHEEL_ORDER.join(",")) плохо("подписи идут не в порядке колеса");

const зелёных = (разметка.match(/wheel-slot green/g) || []).length;
const красных = (разметка.match(/wheel-slot red/g) || []).length;
if (зелёных !== 1) плохо(`зелёных секторов ${зелёных}, а должен быть один (ноль)`);
if (красных !== 18) плохо(`красных секторов ${красных}, а должно быть 18`);

for (const часть of ['class="wheel-pin"', 'class="wheel-ball"', 'class="wheel-ball-orbit"',
                     'id="casino-wheel"', 'id="casino-ball"', 'id="casino-wheel-face"']) {
  if (!разметка.includes(часть)) плохо(`в колесе нет ${часть}`);
}
if (/undefined|NaN/.test(разметка)) плохо("в разметке колеса undefined или NaN");

// --- кость ------------------------------------------------------------------
// Куб кувыркается и падает одинаково убедительно на любой грани. На какой
// именно — видно только если сверить с текстом итога, чего никто не делает.

const грани = DIE_SIDES.map((с) => с.n);
if (грани.length !== 6) плохо(`граней ${грани.length}, а не 6`);
if (new Set(грани).size !== 6) плохо("грани кости повторяются");
for (let n = 1; n <= 6; n++) if (!грани.includes(n)) плохо(`грани ${n} нет на кости`);

// Противоположные грани настоящей кости дают в сумме семь. Пары стоят в
// списке рядом: каждая грань и следом её обратная сторона.
for (let i = 0; i < DIE_SIDES.length; i += 2) {
  const сумма = DIE_SIDES[i].n + DIE_SIDES[i + 1].n;
  if (сумма !== 7) плохо(`грани ${DIE_SIDES[i].n} и ${DIE_SIDES[i + 1].n} дают ${сумма}, а не 7`);
}

// Каждая грань поворачивается ровно вокруг ОДНОЙ оси. Иначе порядок
// сомножителей начинает значить, и промахивается ровно одна грань.
for (const [n, у] of Object.entries(DIE_FACE)) {
  if (у.x !== 0 && у.y !== 0) плохо(`грань ${n} требует оба угла сразу — порядок начнёт значить`);
}

// Поворот к зрителю обязан быть ОБРАТНЫМ тому, которым грань поставлена на
// своё место. Без этой сверки таблица углов проверялась бы сама собой:
// поменяй местами знаки у соседних граней — и всё «сходится», просто кость
// падает тройкой, когда должна четвёркой.
const норм = (a) => (((a % 360) + 360) % 360);
for (const с of DIE_SIDES) {
  const rx = /rotateX\((-?\d+)deg\)/.exec(с.t);
  const ry = /rotateY\((-?\d+)deg\)/.exec(с.t);
  const поставлена = { x: rx ? +rx[1] : 0, y: ry ? +ry[1] : 0 };
  const кзрителю = DIE_FACE[с.n];
  if (!кзрителю) { плохо(`для грани ${с.n} нет поворота к зрителю`); continue; }
  if (норм(поставлена.x + кзрителю.x) !== 0 || норм(поставлена.y + кзрителю.y) !== 0) {
    плохо(`грань ${с.n}: поворот к зрителю не обратен тому, которым она поставлена`);
  }
}
// Шесть разных положений: две грани в одном положении означали бы, что одна
// из них недостижима.
const положения = new Set(Object.values(DIE_FACE).map((у) => `${у.x}|${у.y}`));
if (положения.size !== 6) плохо(`положений куба ${положения.size}, а граней 6`);

for (const [былоX, былоY] of [[0, 0], [123, -456], [3600, 3600], [-1080, 720]]) {
  for (let n = 1; n <= 6; n++) {
    const { x, y } = dieAngles(былоX, былоY, n);
    const остаток = (у, ц) => (((у % 360) - (ц % 360) + 720) % 360);
    if (остаток(x, DIE_FACE[n].x) !== 0 || остаток(y, DIE_FACE[n].y) !== 0) {
      плохо(`кость падает не гранью ${n}: ${x}°/${y}°`);
      break;
    }
    if (x < былоX + 360 * DIE_TURNS_X || y < былоY + 360 * DIE_TURNS_Y) {
      плохо(`грань ${n}: кость кувыркается меньше положенного`);
      break;
    }
  }
}
if (DIE_TURNS_X === DIE_TURNS_Y) плохо("обороты по осям равны — кость крутится как волчок, а не кувыркается");
const мимо = dieAngles(360, 720, 9);
if (мимо.x !== 360 || мимо.y !== 720) плохо("чужая грань всё равно бросает кость");

// Точек на грани ровно столько, сколько на ней написано. Мелочь, которую
// никто не пересчитывает: шестёрка с пятью точками выглядит шестёркой.
for (let n = 1; n <= 6; n++) {
  const точек = (dieFaceHtml(n).match(/class="pip"/g) || []).length;
  if (точек !== n) плохо(`на грани ${n} нарисовано точек: ${точек}`);
  const места = new Set((DIE_PIPS[n] || []).map((м) => м.join(",")));
  if (места.size !== n) плохо(`на грани ${n} точки лежат друг на друге`);
}
const кубик = die3dHtml();
if ((кубик.match(/class="die-side"/g) || []).length !== 6) плохо("у куба нарисованы не шесть граней");
if (!кубик.includes('id="casino-die"')) плохо("куб не за что взять из кода");
if (/undefined|NaN/.test(кубик)) плохо("в разметке кости undefined или NaN");

// --- монета -----------------------------------------------------------------
const монетка = coinHtml();
if ((монетка.match(/class="coin-side/g) || []).length !== 2) плохо("у монеты нарисованы не две стороны");
for (const слово of ["орёл", "решка"]) {
  if (!монетка.includes(`>${слово}<`)) плохо(`на монете не написано «${слово}»`);
}
if (!монетка.includes('id="casino-coin"')) плохо("монету не за что взять из кода");
if (/undefined|NaN/.test(монетка)) плохо("в разметке монеты undefined или NaN");

if (Object.keys(COIN_FACE).length !== 2) плохо("у монеты не две стороны");
// Не «два разных угла», а ровно 0 и 180. У монеты всего две плоскости —
// лицевая и оборотная, повёрнутая на полоборота; любой угол между ними
// показывает монету ребром, то есть ничем. Проверка «лишь бы разные» этого
// не заметила бы: код сошёлся бы сам с собой.
if (норм(COIN_FACE["орёл"]) !== 0) плохо("орёл смотрит не на зрителя");
if (норм(COIN_FACE["решка"]) !== 180) плохо("решка встаёт не оборотной стороной — монета замрёт ребром");
for (const [было, стороны] of [[0, null], [180, null], [-720, null], [1234, null]]) {
  for (const [имя, цель] of Object.entries(COIN_FACE)) {
    const угол = coinAngle(было, имя);
    if ((((угол % 360) - цель + 720) % 360) !== 0) плохо(`монета встаёт не «${имя}»: ${угол}°`);
    if (угол < было + 360 * COIN_TURNS) плохо(`«${имя}»: монета переворачивается меньше положенного`);
  }
}
if (coinAngle(720, "ребро") !== 720) плохо("чужая сторона всё равно вертит монету");

// --- бросок обязан кончиться -------------------------------------------------
// Самая дорогая из здешних поломок, и она уже случилась: flipCoin крутил
// монету и НЕ звал обработчик конца. Монета садилась, а экран оставался в
// полёте навсегда — итога нет, баланс прежний, «Играть» не нажать.
//
// Прежняя проверка смотрела, что обработчик ПЕРЕДАЮТ в бросок, и была
// довольна. Передают — да; зовут ли внутри — она не спрашивала. Теперь
// спрашивает: бросок зовут по-настоящему и ждут звонка.
{
  const броски = [
    ["колесо", (кончилось) => spinWheel(7, true, кончилось), "#casino-wheel"],
    ["кость", (кончилось) => rollDie(4, true, кончилось), "#casino-die"],
    ["монета", (кончилось) => flipCoin("решка", true, кончилось), "#casino-coin"],
  ];
  for (const [имя, бросить, узел] of броски) {
    for (const есть_узел of [true, false]) {
      // Узел на месте и узла нет — оба пути обязаны кончиться. Второй бывает,
      // когда человек ушёл со вкладки, пока летел ответ сервера.
      for (const ключ of Object.keys(узлы)) delete узлы[ключ];
      if (есть_узел) global.$(узел);
      const прежний = global.$;
      if (!есть_узел) global.$ = (сел) => (сел === узел ? null : прежний(сел));

      let позвали = false;
      бросить(() => { позвали = true; });
      global.$ = прежний;

      // Ждём таймеры: длительность нулевая, но setTimeout всё равно уводит
      // вызов на следующий тик.
      const проверить = () => {
        if (!позвали) {
          плохо(`${имя}${есть_узел ? "" : " (узла нет)"}: бросок не позвал обработчик `
                + "конца — экран останется «в полёте» навсегда");
        }
      };
      // Синхронно проверить нельзя, поэтому копим и смотрим ниже.
      ожидания.push(проверить);
    }
  }
}

setTimeout(() => {
  ожидания.forEach((п) => п());
  console.log(ошибок
    ? `\nошибок: ${ошибок}`
    : "✓ казино: колесо, кость и монета встают своей стороной и доводят бросок до конца");
  process.exit(ошибок ? 1 : 0);
}, 20);
