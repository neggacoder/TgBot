"""Какие чаты у бота свои.

Чатов ровно два, и у каждого своя роль:

* **рабочий** (настройка `complaint_chat_id`, команда «жалобы сюда») — здесь
  бот работает на все сто: игры, экономика, модерация, роли, чистка;
* **чат заявок** (настройка `notify_chat_id`, команда «чат сюда») — здесь он
  молчит на всё, кроме заявок на вступление: кнопки «принять/отклонить» и
  ответы админов заявителю.

Любой третий чат — чужой.

Модуль заведён потому, что настройки читались россыпью: сто семь мест в одном
bot.py. Пока их столько, перепутать рабочий чат с заявочным ничего не стоит —
так уже было с ролями и чисткой, которые брали notify_chat_id и молча работали
не там. Одно место — одна правда.

Кэша здесь НЕТ намеренно. Чат меняют командой на ходу, и запомненное значение
пережило бы перепривязку: бот продолжал бы считать рабочим старый чат, а
человек видел бы, что команда «сработала». Чтение идёт через
db.fetch_settings() — у него одна строка настроек на оба процесса, бота и
панель.
"""

from __future__ import annotations

from typing import Optional

import db


async def _настройки() -> dict:
    """Строка настроек или пустой словарь.

    Ошибку глотаем: бот обязан подниматься и с недоступной базой. Без настроек
    он просто не считает своим ни один чат — это безопасный исход, в отличие
    от падения на первом же сообщении.
    """
    try:
        return await db.fetch_settings() or {}
    except Exception:
        return {}


def _как_число(значение) -> Optional[int]:
    """Идентификатор чата из настройки. Пусто и мусор — одинаково «не задан»:
    в базе тут бывает и NULL, и пустая строка от старых версий."""
    if значение in (None, "", 0):
        return None
    try:
        return int(значение)
    except (TypeError, ValueError):
        return None


async def work_chat_id() -> Optional[int]:
    """Рабочий чат («жалобы сюда») или None, если ещё не привязан."""
    return _как_число((await _настройки()).get("complaint_chat_id"))


async def gate_chat_id() -> Optional[int]:
    """Чат заявок («чат сюда») или None."""
    return _как_число((await _настройки()).get("notify_chat_id"))


async def is_work_chat(chat_id: int) -> bool:
    """Тот ли это чат, где бот работает полностью."""
    рабочий = await work_chat_id()
    return рабочий is not None and chat_id == рабочий


async def is_known_chat(chat_id: int) -> bool:
    """Свой ли это чат вообще — рабочий или заявок.

    Одним запросом настроек на оба: раздельные вызовы читали бы строку дважды
    на каждое сообщение.
    """
    настройки = await _настройки()
    свои = {
        _как_число(настройки.get("complaint_chat_id")),
        _как_число(настройки.get("notify_chat_id")),
    } - {None}
    return chat_id in свои
