"""Рубильники владельца — те, что должны работать одинаково из чата и с сайта.

Пока такой рубильник один: «+бесконечность». Модуль всё равно отдельный,
потому что дело здесь не в размере, а в том, ГДЕ лежит правда.

Раньше список владельцев с бесконечными деньгами жил множеством в памяти бота
и читался из базы ровно один раз — при запуске. Пока переключали только
командой в чате, это работало: тот же процесс, что читает, тот же и пишет.
Стоит появиться второму входу — кнопке на сайте, — и всё разъезжается молча:
панель пишет в базу, бот продолжает смотреть в своё множество, кнопка выглядит
сработавшей, а деньги списываются как раньше. Заметить это можно только по
балансу, и то не сразу.

Поэтому здесь, как и в chats, КЭША НЕТ намеренно: правда одна и лежит в базе,
читается на каждый вопрос. Лишнее чтение одной строки по ключу дешевле, чем
рубильник, который врёт.

Второе, что решается только здесь, — ЧТЕНИЕ ПЕРЕД ЗАПИСЬЮ. Значение общее на
всех владельцев: это список идентификаторов через запятую. Тот, кто пишет из
своего снимка, затирает чужие изменения — владелец A включил себе с сайта,
владелец B выключил себе в чате, и запись B, собранная из его старого списка,
молча убрала бы A. Поэтому список всегда перечитывается перед правкой.
"""

from __future__ import annotations

import logging
from typing import Optional

import db

logger = logging.getLogger(__name__)

# Ключ в bot_data. Общий для бота и панели — разъедься он, и два входа
# переключали бы разные рубильники, каждый со своим списком.
INFINITE_MONEY_KEY = "infinite_money_users"


def _разобрать(значение: Optional[str]) -> set[int]:
    """Список идентификаторов через запятую. Мусор пропускаем молча: в базе
    лежит текст, и одна битая запись не должна лишать бесконечности всех."""
    if not значение:
        return set()
    найдено = set()
    for кусок in значение.split(","):
        кусок = кусок.strip()
        if кусок.lstrip("-").isdigit():
            найдено.add(int(кусок))
    return найдено


async def infinite_money_users() -> set[int]:
    """Кому сейчас включены бесконечные деньги.

    Ошибку чтения глотаем и отдаём пустое множество: недоступная база не
    должна раздать бесконечные деньги — безопасный исход тот, где их нет ни
    у кого.
    """
    try:
        row = await db.get_data(INFINITE_MONEY_KEY)
    except Exception as exc:
        logger.warning("не прочитал список бесконечных денег: %s", exc)
        return set()
    return _разобрать(row.get("data_value") if row else None)


async def has_infinite_money(user_id: Optional[int]) -> bool:
    if not user_id:
        return False
    return user_id in await infinite_money_users()


async def set_infinite_money(user_id: int, enabled: bool) -> bool:
    """Включает или выключает бесконечные деньги одному владельцу.

    Список ПЕРЕЧИТЫВАЕТСЯ перед правкой: собранная из своего снимка запись
    затёрла бы чужие изменения, и понять это было бы нечем — чужой рубильник
    просто перестал бы работать.

    Возвращает новое состояние.
    """
    сейчас = await infinite_money_users()
    if enabled:
        сейчас.add(user_id)
    else:
        сейчас.discard(user_id)
    await db.set_data(INFINITE_MONEY_KEY, ",".join(str(u) for u in sorted(сейчас)))
    return enabled
