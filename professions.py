"""Профессии: правила восстановления энергии, настроения и здоровья.

Здесь только ЧИСЛА И ПРАВИЛА, без БД и Telegram — как pets.py и businesses.py
рядом. Сама профессия (список, смены, опыт) живёт в bot.py; сюда вынесено то,
что нужно и обработчикам, и хранилищу.

Восстановление считается ЛЕНИВО, ровно как сытость питомца: в базе лежит
значение и момент последнего пересчёта, а текущее выводится из прошедших
часов. Фонового цикла нет — бот может простоять сутки и ничего не потеряет,
при первом обращении досчитает.

Направление обратное питомцам: там значение падает, здесь растёт. Поэтому и
потолок здесь сверху (MAX_STAT), а не снизу.
"""

from __future__ import annotations

from datetime import timedelta

MAX_STAT = 100

# Сколько восстанавливается в час. База — тем, у кого профессии нет вовсе:
# иначе новичок, ушедший в ноль, остался бы там навсегда и не смог бы даже
# начать работать. Каждый уровень профессии добавляет по единице: опытный
# работник отдыхает быстрее.
REGEN_BASE_PER_HOUR = 4
REGEN_PER_LEVEL = 1


def regen_per_hour(prof_level: int) -> int:
    """Скорость восстановления при этом уровне профессии.

    prof_level=0 означает «профессии нет» — вызывающий передаёт ноль сам,
    потому что в базе уровень равен единице и у тех, кто ещё не устроился.
    """
    return REGEN_BASE_PER_HOUR + REGEN_PER_LEVEL * max(0, int(prof_level or 0))


def restored(value: int, hours: float, per_hour: int) -> int:
    """Во что превратилось значение через hours часов. Выше MAX_STAT не растёт.

    Округление к ближайшему, а не отбрасыванием дроби, — по той же причине,
    что и у питомцев (pets.decayed): иначе почти целый час восстановления
    пропадал бы при каждом пересчёте.

    Отрицательное время ничего не добавляет: часы бота и базы могут
    разъехаться, и «восстановление назад» из этого получаться не должно.
    """
    current = max(0, min(int(value), MAX_STAT))
    if hours <= 0:
        return current
    return max(0, min(int(round(current + per_hour * hours)), MAX_STAT))


def hours_to_full(value: int, per_hour: int) -> float:
    """Через сколько часов значение дойдёт до потолка. 0 — уже полное."""
    missing = MAX_STAT - max(0, min(int(value), MAX_STAT))
    if missing <= 0 or per_hour <= 0:
        return 0.0
    return missing / per_hour


