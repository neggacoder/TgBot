"""Русский текст в командах: «е» и «ё» — одна и та же буква.

Здесь только ПРАВИЛА РАЗБОРА, без БД и Telegram — как pets.py и pins.py рядом.

Зачем. Команды сравниваются через casefold(), который приводит регистр, но не
ё к е. Из-за этого набор триггеров с «чёрное» не узнавал «черное», а
«пет кормить всё» не совпадало с «все». Половина людей вообще не набирает ё,
вторая половина набирает — и команда работала только у одной из них.

Раньше это чинили поштучно: «нал[её]т», «орёл|орел», отдельные синонимы
питомцев. Каждая новая команда со словом на ё приносила ту же ошибку заново,
потому что чинили симптом. Здесь — одно правило на весь бот.

Наборы триггеров нормализуются ОДИН РАЗ при сборке (см. bot._COMMAND_PREFIX_INDEX),
а не при каждом сравнении: иначе триггер, написанный через ё, стал бы
недостижим для обоих написаний сразу — вход-то уже приведён к е.

ВАЖНО: сам текст пользователя мы НЕ переписываем. Цитаты, статистика, имена
питомцев, названия товаров и фильтр слов должны видеть ровно то, что человек
написал. Нормализуется только сравнение.
"""

from __future__ import annotations

import re
from typing import Optional


def yo(text: Optional[str]) -> str:
    """Текст без «ё» — для СРАВНЕНИЯ, а не для показа и не для хранения."""
    if not text:
        return ""
    return text.replace("ё", "е").replace("Ё", "Е")


def _yo_class(char: str) -> str:
    return "[еЕёЁ]" if char in "еЕёЁ" else char


def yo_pattern(pattern: str) -> str:
    """Делает шаблон нечувствительным к ё: каждая «е»/«ё» вне символьного
    класса превращается в [еЕёЁ].

    Классы не трогаем намеренно. Во-первых, написанные вручную «[её]» уже
    правильные, и вложить в них ещё один класс значило бы сломать шаблон.
    Во-вторых, автор класса перечислил ровно те буквы, которые хотел, — не
    наше дело дописывать туда свои.

    Флаг re.IGNORECASE регистр покрывает и сам, но класс с обоими регистрами
    делает шаблон верным и без флага.
    """
    out = []
    in_class = False
    escaped = False
    for char in pattern:
        if escaped:
            out.append(char)
            escaped = False
            continue
        if char == "\\":
            out.append(char)
            escaped = True
            continue
        if char == "[":
            in_class = True
        elif char == "]":
            in_class = False
        out.append(char if in_class else _yo_class(char))
    return "".join(out)


def rx(pattern: str, flags: int = 0) -> re.Pattern:
    """re.compile для команд: «е» и «ё» в шаблоне совпадают с обеими буквами.

    Шаблоны без русских е/ё проходят насквозь неизменными, поэтому заменять
    re.compile на rx можно везде подряд, не разбирая каждый случай.
    """
    return re.compile(yo_pattern(pattern), flags)
